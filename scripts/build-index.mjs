import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const MARKER = "// Generated by scripts/build-index.mjs. Do not edit.";
const src = fileURLToPath(new URL("../src/", import.meta.url));
const apps = join(src, "apps");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

// Drop promise flavors from a previous run. CI replaces src/apps wholesale,
// but local builds must not keep modules for services that no longer exist.
// Only remove files this script owns (checked by marker), never a `promise.ts`
// that protoc-gen-ts_proto may have emitted for a `promise.proto`.
for (const file of walk(apps)) {
  if (basename(file) !== "promise.ts") continue;
  if (readFileSync(file, "utf8").startsWith(MARKER)) rmSync(file);
}

const generatedFiles = walk(apps)
  .map((file) => relative(apps, file).split("\\").join("/"))
  .filter((file) => file.endsWith(".ts"))
  .sort();

// Root barrel: every generated protobuf module (grpc-js style, the default).
// The promise flavors stay reachable through `./apps/<...>/<service>/promise`.
writeFileSync(
  join(src, "index.ts"),
  `${generatedFiles
    .map((file) => `export * from "./apps/${file.replace(/\.ts$/, ".js")}";`)
    .join("\n")}\n`,
);

const UNARY = "handleUnaryCall";
const SERVER_STREAMING = "handleServerStreamingCall";
const CLIENT_STREAMING = "handleClientStreamingCall";
const BIDI_STREAMING = "handleBidiStreamingCall";

function parseInterfaceMembers(source, service) {
  const iface = source.statements.find(
    (node) => ts.isInterfaceDeclaration(node) && node.name.text === `${service}Server`,
  );
  if (!iface) return [];

  return iface.members.flatMap((member) => {
    if (!ts.isPropertySignature(member) || !member.type) return [];
    if (!ts.isTypeReferenceNode(member.type)) return [];
    return [
      {
        name: member.name.getText(source),
        kind: member.type.typeName.getText(source),
        args: (member.type.typeArguments ?? []).map((arg) => arg.getText(source)),
      },
    ];
  });
}

function importSpecifiers(source) {
  const specifiers = new Map();
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    if (!ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const bindings = statement.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;
    for (const element of bindings.elements) {
      specifiers.set(element.name.text, statement.moduleSpecifier.text);
    }
  }
  return specifiers;
}

function relativeSpecifier(fromDir, serviceDir, specifier) {
  const target = resolve(serviceDir, specifier).split(sep).join("/");
  let rel = relative(fromDir, target).split(sep).join("/");
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return rel;
}

function promiseSignature(method) {
  const [request, response] = method.args;
  switch (method.kind) {
    case UNARY:
      return `  ${method.name}(request: ${request}, options?: CallOptions): Promise<${response}>;`;
    case SERVER_STREAMING:
      return `  ${method.name}(request: ${request}, options?: CallOptions): AsyncIterable<${response}>;`;
    case CLIENT_STREAMING:
      return `  ${method.name}(requests: AsyncIterable<${request}>, options?: CallOptions): Promise<${response}>;`;
    case BIDI_STREAMING:
      return `  ${method.name}(requests: AsyncIterable<${request}>, options?: CallOptions): AsyncIterable<${response}>;`;
    default:
      return undefined;
  }
}

for (const file of generatedFiles) {
  const sourceText = readFileSync(join(apps, file), "utf8");
  const services = [...sourceText.matchAll(/^export type ([A-Za-z0-9_]+) = typeof \1;$/gm)].map(
    (match) => match[1],
  );
  if (services.length === 0) continue;

  const source = ts.createSourceFile(file, sourceText, ts.ScriptTarget.Latest, true);
  const specifiers = importSpecifiers(source);
  const serviceDir = dirname(join(apps, file));
  const outDir = join(apps, file.slice(0, -".ts".length));
  const usedTypes = new Set();
  const serviceBlocks = [];

  for (const definition of services) {
    // ts-proto names grpc-js definitions `<Service>Service`, so one `Service`
    // suffix yields the protobuf service name.
    const service = definition.replace(/Service$/, "");
    const methods = parseInterfaceMembers(source, service);

    const signatures = methods.flatMap((method) => {
      const line = promiseSignature(method);
      if (!line) return [];
      for (const type of method.args) usedTypes.add(type);
      return [line];
    });

    serviceBlocks.push(
      // An explicit interface (instead of `Client<typeof ...>`) gives editors a
      // concrete declaration to jump to from `client.getUser(...)`.
      `export interface ${service}Client {`,
      ...signatures,
      "}",
      "",
      `export function create${service}Client(`,
      "  address: string,",
      "  credentials?: ChannelCredentials,",
      "  options?: ChannelOptions,",
      `): ${service}Client {`,
      `  return createClient(${definition}, createChannel(address, credentials, options));`,
      "}",
    );
  }

  const importsBySpecifier = new Map();
  for (const type of usedTypes) {
    const specifier = specifiers.get(type);
    if (!specifier) continue;
    const rel = relativeSpecifier(outDir, serviceDir, specifier);
    importsBySpecifier.set(rel, [...(importsBySpecifier.get(rel) ?? []), type]);
  }

  const parts = [
    MARKER,
    'import { createChannel, createClient } from "nice-grpc";',
    'import type { CallOptions, ChannelCredentials, ChannelOptions } from "nice-grpc";',
    `import { ${services.join(", ")} } from "../${basename(file, ".ts")}.js";`,
    ...[...importsBySpecifier].map(
      ([specifier, types]) => `import type { ${types.join(", ")} } from "${specifier}";`,
    ),
    "",
    ...serviceBlocks,
  ];

  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "promise.ts"), `${parts.join("\n")}\n`);
}
