import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../src/", import.meta.url));
const files = readdirSync(join(src, "apps"), { recursive: true })
  .filter((file) => file.endsWith(".ts"))
  .map((file) => file.split("\\").join("/"))
  .sort();

const generated = files
  .map((file) => `export * from "./apps/${file.replace(/\.ts$/, ".js")}";`)
  .join("\n");

// Collect `<Service>Definition` exports so every service also gets a
// one-line, fully typed Promise factory (nice-grpc's `createClient` with an
// internally created channel).
const factories = [];
for (const file of files) {
  const source = readFileSync(join(src, "apps", file), "utf8");
  const modulePath = `./apps/${file.replace(/\.ts$/, ".js")}`;

  for (const match of source.matchAll(/export const ([A-Za-z0-9_]+ServiceDefinition) = \{/g)) {
    const definition = match[1];
    factories.push({
      definition,
      modulePath,
      factory: `create${definition.replace(/Definition$/, "")}Client`,
    });
  }
}

const clients = [
  "// Generated by scripts/build-index.mjs. Do not edit.",
  'import { createChannel, createClient } from "nice-grpc";',
  'import type { ChannelCredentials, ChannelOptions, Client } from "nice-grpc";',
  ...factories.map(({ definition, modulePath }) => `import { ${definition} } from "${modulePath}";`),
];

for (const { factory, definition } of factories) {
  clients.push(
    [
      "",
      `export function ${factory}(`,
      "  address: string,",
      "  credentials?: ChannelCredentials,",
      "  options?: ChannelOptions,",
      `): Client<typeof ${definition}> {`,
      `  return createClient(${definition}, createChannel(address, credentials, options));`,
      "}",
    ].join("\n"),
  );
}

// `promise.ts` and `clients.ts` are generated/hand-written scaffold, not
// generated protobuf code. They are appended so the root entry always exposes
// the nice-grpc client helpers and per-service factories.
writeFileSync(
  join(src, "index.ts"),
  `${[generated, 'export * from "./promise.js";', 'export * from "./clients.js";']
    .filter(Boolean)
    .join("\n")}\n`,
);
writeFileSync(join(src, "clients.ts"), `${clients.join("\n")}\n`);
