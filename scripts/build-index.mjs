import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const MARKER = "// Generated by scripts/build-index.mjs. Do not edit.";
const src = fileURLToPath(new URL("../src/", import.meta.url));
const apps = join(src, "apps");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

// Drop promise flavors from a previous run. CI replaces src/apps wholesale,
// but local builds must not keep modules for services that no longer exist.
// Only remove files this script owns (checked by marker), never a `promise.ts`
// that protoc-gen-ts_proto may have emitted for a `promise.proto`.
for (const file of walk(apps)) {
  if (basename(file) !== "promise.ts") continue;
  if (readFileSync(file, "utf8").startsWith(MARKER)) rmSync(file);
}

const generatedFiles = walk(apps)
  .map((file) => relative(apps, file).split("\\").join("/"))
  .filter((file) => file.endsWith(".ts"))
  .sort();

// Root barrel: every generated protobuf module (grpc-js style, the default).
// The promise flavors stay reachable through `./apps/<...>/<service>/promise`.
writeFileSync(
  join(src, "index.ts"),
  `${generatedFiles
    .map((file) => `export * from "./apps/${file.replace(/\.ts$/, ".js")}";`)
    .join("\n")}\n`,
);

for (const file of generatedFiles) {
  const source = readFileSync(join(apps, file), "utf8");
  const services = [...source.matchAll(/^export type ([A-Za-z0-9_]+) = typeof \1;$/gm)].map(
    (match) => match[1],
  );
  if (services.length === 0) continue;

  const moduleName = basename(file, ".ts");
  const serviceModule = `../${moduleName}.js`;
  const lines = [
    MARKER,
    'import { createChannel, createClient } from "nice-grpc";',
    'import type { ChannelCredentials, ChannelOptions, Client } from "nice-grpc";',
    `import { ${services.join(", ")} } from "${serviceModule}";`,
  ];

  for (const definition of services) {
    // ts-proto names grpc-js definitions `<Service>Service`, so one `Service`
    // suffix yields the protobuf service name.
    const service = definition.replace(/Service$/, "");
    lines.push(
      "",
      `export type ${service}Client = Client<typeof ${definition}>;`,
      "",
      `export function create${service}Client(`,
      "  address: string,",
      "  credentials?: ChannelCredentials,",
      "  options?: ChannelOptions,",
      `): ${service}Client {`,
      `  return createClient(${definition}, createChannel(address, credentials, options));`,
      "}",
    );
  }

  const outDir = join(apps, file.slice(0, -".ts".length));
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "promise.ts"), `${lines.join("\n")}\n`);
}
